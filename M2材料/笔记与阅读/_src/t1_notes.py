A(H2("6. ★ 核心数学：六个步骤", "T1-07"))
A(NOTE("这一页讲义标着 *** CORE MATH ***，是 T1 最可能出大题的地方。"))

A(H3("Step 1 · 从数据开始"))
A(P("数据集 X 有 n 个观测、d 个特征。**每一行是一个观测，每一列是一个特征。**"))

A(H3("Step 2 · 中心化"))
A(EQ("µ = (1/n) Σ_{i=1}^{n} x_{i}",
     "X_{c} = X − 1_{n} µ^{T}      （1_{n} 是 n×1 的全 1 向量）"))
A(P("中心化把数据中心搬到原点，于是方差描述的是**围绕特征均值的散布**，"
    "而不是到某个任意原点的距离。"))
A(CAL("t", "⭐ 一个随手就能做的自检",
      "**X_{c} 的每一列加起来必须等于 0**（允许极小的舍入误差）。手算时先验这一步，能挡掉大半的错。"))

A(H3("Step 3 · 构造协方差矩阵"))
A(EQ("Σ = (1/(n−1)) · X_{c}^{T} X_{c}"))
A(P("Σ 是对称的 d×d 矩阵。**对角元是某个特征自己的方差；非对角元表示两个特征怎样共同变化。**"))

A(H3("Step 4 · 为什么会冒出特征向量（这一段要会推）"))
A(P("取任意**单位**方向 v（即 v^{T}v = 1），把每个中心化观测投上去："))
A(EQ("z = X_{c} v"))
A(P("这些一维得分的样本方差是："))
A(EQ("Var(z) = (1/(n−1)) z^{T}z = v^{T} Σ v"))
A(P("PCA 问的就是：**哪个单位方向能让这个量最大？**解这个带约束的最大化问题，得到特征值关系："))
A(EQ("Σ v = λ v"))
A(CAL("k", "★★★ 这一步的结论要能背出来",
      "**一个特征向量给出的方向，其投影方差就等于它的特征值。**",
      "所以**特征值最大的那个特征向量就是第一主方向**，因为它产生最大的投影方差。"))
A(CAL("t", "⭐ 几何读法（答简答题时很好用）",
      "想象一根一维的轴穿过中心化后的点云转动，把每个点投上去。"
      "**PCA 挑的就是让这些投影坐标散得最开的那个角度。**"
      "协方差的特征问题，只是「不用一个个角度去试」的矩阵算法。"))

A(H3("Step 5 · 分解并排序"))
A(UL(["求 Σ 的特征值 λ_{1}…λ_{d} 与对应的**单位**特征向量 v_{1}…v_{d}；",
      "按降序排 λ_{1} ≥ λ_{2} ≥ … ≥ λ_{d}；",
      "特征向量定义主方向，**每个方向上挂着的特征值就是对应得分的方差**。"]))
A(P("主方向两两正交。对拟合用的这批数据，**成分得分是不相关的**——"
    "但这**不保证**所有非线性依赖或任务相关的信息都消失了。"))

A(H3("Step 6 · 选成分、投影、重构"))
A(P("取前 k 个特征向量放进 d×k 的矩阵 W_{k}。成分 j 的**解释方差比**是："))
A(EQ("r_{j} = λ_{j} / Σ_{l=1}^{d} λ_{l}",
     "k 个成分的累计保留方差 = Σ_{j=1}^{k} r_{j}"))
A(EQ("Z = X_{c} W_{k}                    （n×k 得分矩阵）",
     "X̂ = Z W_{k}^{T} + 1_{n} µ^{T}        （回到原特征空间的重构）"))
A(CAL("w", "⚠ 重构时**必须把均值加回去**",
      "`Z W^{T}` 只回到**中心化**的空间。漏掉 `+ µ` 是手算大题最常见的扣分点之一。"))

A(H3("★ 开算之前必须核对的五条约定（讲义标为 exam-critical）"))
A(TB(["约定", "内容"], [
    ["① 先中心化", "构造散布矩阵或协方差矩阵**之前**，先把每个特征的均值减掉"],
    ["② 散布 vs 协方差",
     "S = X_{c}^{T}X_{c} 和 S/(n−1) 的**特征向量完全相同**；特征值差一个 (n−1) 的因子，"
     "但**解释方差比一模一样**"],
    ["③ 归一化", "投影之前要用**单位**特征向量"],
    ["④ 投的是中心化数据", "Z = X_{c}W；均值**只在重构时**加回去"],
    ["⑤ 该缩放时才缩放", "特征单位或量程不可比时才标准化"],
]))
A(CAL("t", "⭐ 约定 ② 在考试里的用法",
      "题目给的是散布矩阵 S（不除 n−1）时，**直接对 S 做特征分解即可**——"
      "方向一样，比值一样，不用先除。这样能省掉分数运算，还不容易算错。"))

