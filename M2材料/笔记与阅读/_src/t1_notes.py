A(H2("7. 手算例题 A：讲义的 PCA by hand", "T1-09"))
A(NOTE("这个例子**刻意**造得两个主方向都有变异，所以保留一个成分只能留住大部分、留不住全部方差 ——"
       "比「所有点正好共线」的例子更能说明成分选择。"))
A(EX("题：把下面四个二维观测投到一维",
     TB(["观测", "x", "y"], [["1", "−3", "0"], ["2", "3", "0"],
                            ["3", "0", "−1"], ["4", "0", "1"]], tight=True, numcols=(1, 2)),
     STEP("第 1 步", "均值与中心化矩阵。",
          EQ("µ = (0, 0)      ⇒  X_{c} = X（本来就已经居中）"),
          "自检：两列各自加起来都是 0。✓"),
     STEP("第 2 步", "散布矩阵与样本协方差。",
          EQ("S = X_{c}^{T}X_{c} = [[18, 0], [0, 2]]",
             "Cov = S/(n−1) = S/3 = [[6, 0], [0, 2/3]]"),
          "**因为是对角矩阵，特征值直接就在对角线上**，不用解特征方程。"),
     STEP("第 3 步", "特征值与单位特征向量（按降序）。",
          EQ("λ_{1} = 6,    v_{1} = (1, 0)^{T}",
             "λ_{2} = 2/3,  v_{2} = (0, 1)^{T}")),
     STEP("第 4 步", "解释方差比。",
          EQ("r_{1} = 6 / (6 + 2/3) = 6 / (20/3) = 0.9",
             "r_{2} = (2/3) / (20/3) = 0.1"),
          "**一个成分就达到 90% 的保留方差目标。**"),
     STEP("第 5 步", "投影到 PC1 并用一个成分重构。",
          EQ("z = X_{c}v_{1} = (−3, 3, 0, 0)^{T}",
             "X̂ = z v_{1}^{T} + µ = [[−3,0], [3,0], [0,0], [0,0]]")),
     STEP("第 6 步", "谁丢了信息？",
          "**观测 3 和 4 在第二个特征上被重构到了均值（0）**，它们之间的差别彻底消失了。",
          EQ("总平方重构误差 = (−1−0)² + (1−0)² = 2",
             "校验：被丢掉的特征值 × (n−1) = (2/3) × 3 = 2  ✓")),
     ))
A(CAL("k", "★★ 这题真正要考的点",
      "**保留 90% 的方差，不等于保留了每个特征的 90%，也不等于保留了每一个与应用相关的信号。**",
      "这里第二个特征的变异在秩一重构里**完全消失**。"
      "如果应用恰好要区分观测 3 和 4，那么「90% 方差」这个目标就是不够的。"))
A(CAL("t", "⭐ 一个能当校验用的恒等式（手算时很值钱）",
      "**丢掉成分 j 造成的总平方重构误差 = λ_{j} × (n−1)**（λ 取自样本协方差矩阵）。"
      "或者更直接：**= 散布矩阵 S 的对应特征值**。这里 S 的第二个特征值就是 2。"))

