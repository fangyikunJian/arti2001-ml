A(H3("E 步：估计责任度"))
A(EQ("r_{ik} = π_{k} N(x_{i} | µ_{k}, Σ_{k}) / Σ_{j=1}^{K} π_{j} N(x_{i} | µ_{j}, Σ_{j})"))
A(UL(["在**同一个观测** x_{i} 上，算**每一个**成分的高斯密度；",
      "各自乘上该成分**当前的**权重 π_{k}；",
      "把这些加权密度相加，得到分母 p(x_{i})；",
      "每个加权密度除以这个**公共分母**。对每个观测重复一遍。"], True))
A(P("这就是**贝叶斯公式**：**后验成员度 = 先验权重 × 成分密度 ÷ 混合密度**。"
    "一个观测的各责任度加起来是 1。它们是**软后验指派，不是观测到的或固定的类标签**。"))

A(H3("M 步：用加权统计量更新参数"))
A(CAL("k", "★★★ 什么是「有效计数」（必考概念）",
      "如果成员是已知的，每个观测对某成分的计数贡献要么是 1 要么是 0。",
      "**GMM 里成员是不确定的：责任度 0.9 就贡献 0.9 个计数。**"
      "把这些分数贡献加起来，就得到 **N_{k} = Σ_{i} r_{ik}**，即成分 k 期望生成的观测数。",
      "**它不是「概率超过某阈值的点数」，也不意味着某个观测被物理地切开。**",
      "因为每个观测在所有成分上总共贡献 1，所以 **Σ_{k} N_{k} = N**。"))
A(CAL("w", "⚠⚠ M 步内部的顺序不能乱",
      "**整个 M 步里都要保持 E 步算出的责任度不变。**",
      "**先算有效计数 → 再算权重和均值 → 最后用「新均值」算协方差。**"))
A(EQ("N_{k} = Σ_{i} r_{ik}",
     "π_{k} = N_{k} / N",
     "µ_{k} = (1/N_{k}) Σ_{i} r_{ik} x_{i}",
     "Σ_{k} = (1/N_{k}) Σ_{i} r_{ik} (x_{i} − µ_{k})(x_{i} − µ_{k})^{T}"))
A(P("用大白话说：**新权重是这个成分占数据集的份额；新均值是它的责任度加权平均；"
    "新协方差是围绕「那个新均值」的责任度加权散布。**"
    "均值和协方差的和要除以 N_{k}，因为 N_{k} 正是被平均的总权重。这些更新要求 N_{k} > 0。"))
A(CAL("w", "⚠⚠⚠ 三个最高频的扣分点",
      UL(["**分母是 N_{k}，不是 N**（这是加权平均，不是普通平均）；",
          "**协方差要用「刚更新完的新均值」**，不是旧均值；",
          "**除以 N_{k}，不是 N_{k} − 1** —— 这是**极大似然**更新，不是无偏样本方差公式。"])))
A(CAL("t", "⭐ 多特征时的唯一改动",
      "把 (x_{i} − µ_{k})² 换成**外积** (x_{i} − µ_{k})(x_{i} − µ_{k})^{T}。其余一字不改。"))
A(CAL("w", "⚠ 成分标签是任意的",
      "**交换两个拟合成分的编号，不改变混合密度。**"
      "要通过它估计出的参数、以及它描述的那些观测来解释一个成分（通常按均值排序后再比较）。"))

