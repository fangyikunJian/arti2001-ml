A(H2("7. DBSCAN：密度是局部定义的", "T2-04"))
A(P("**DBSCAN**（Density-Based Spatial Clustering of Applications with Noise）"
    "能发现**非质心形状**的稠密区域，并且可以把区域之外的观测**留着不指派**。"
    "它**不需要预先给出簇数**，但结果仍然取决于距离表示以及 eps 与 MinPts 两个参数。"))
A(CAL("k", "★ 密度的定义是「局部」的",
      "**当一个点的 eps-邻域里至少有 MinPts 个观测时，它就处在稠密区域。**",
      "连通的核心点构成簇的骨架；附近的非核心点可以作为**边界点**加入；"
      "落在所有已发现稠密区域之外的观测，在当前设置下被标为**噪声**。"))

A(H3("四步高层流程"))
A(UL(["**访问一个未处理的观测**：检查所有与它距离 ≤ eps 的观测，**包括它自己**；",
      "**判定三类点**（见下表）；",
      "**从核心点扩张**：递归地把通过相邻核心点可达的观测加进来。"
      "**边界点加入簇，但不扩张簇。**",
      "**重复**：访问下一个未处理的观测，直到所有观测都被检查过。"], True))
A(TB(["类型", "判据"], [
    ["核心点 Core", "**它自己的邻域里至少有 MinPts 个观测**"],
    ["边界点 Border", "它**在某个核心点的邻域内**，但它自己不是核心点"],
    ["噪声点 Noise", "既不是核心点，也不在任何核心点的邻域内"],
]))
A(CAL("w", "⚠⚠ 三个最容易丢分的细节",
      UL(["**邻域包含点自己**。scikit-learn 的 `min_samples` 也是**把该点算在内**的，"
          "和本课的约定一致；",
          "**只有核心点才能继续密度可达链。**边界点进了簇就到此为止；",
          "**先被标成噪声的点，可能后来变成边界点。**"
          "如果 A 在 B 之前被访问，A 可能被**临时**标为噪声；"
          "等 B 被认出是核心点、簇扩张过来，A 就成了边界点。"])))

