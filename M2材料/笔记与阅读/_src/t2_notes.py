A(H2("3. k-means：算法与目标函数", "T2-03"))
A(H3("前提：欧氏距离"))
A(EQ("d(x, y) = √( (x_{1}−y_{1})² + (x_{2}−y_{2})² + … + (x_{n}−y_{n})² ) = √( Σ_{i=1}^{n}(x_{i}−y_{i})² )"))
A(CAL("t", "⭐ 手算时不用开根号",
      "指派步只是**比大小**，而平方根是单调的，所以**直接比平方距离**即可。"
      "Tutorial 的参考答案也是这么做的，还省掉了无理数。"))

A(H3("四步算法"))
A(TB(["步骤", "内容"], [
    ["① 初始化", "选 k（靠领域知识或肘部法等）；初始化质心。"
                "实践中常用 **k-means++**，因为它把起始中心**拉开**。"
                "不同起点会收敛到不同局部解，所以要**多次初始化并保留 WCSS 最低的那次**"],
    ["② 指派", "对每个点算到每个质心的欧氏距离，**归给最近的那个质心**"],
    ["③ 更新", "每个簇的新质心是**所有被指派进来的点的均值**：µ_{i} = (1/m)Σ_{j=1}^{m} x_{j}"],
    ["④ 迭代", "重复 ②③，直到：指派不再变化 / 质心稳定 / 达到最大迭代次数"],
]))

A(H3("★★ 为什么这两步有效：目标函数"))
A(EQ("WCSS = Σ_{i=1}^{k} Σ_{x∈C_{i}} d(x, µ_{i})²        （也叫 inertia / 惯性）"))
A(CAL("k", "★★★ 两步为什么单调不增（大题常考）",
      UL(["**指派步不会增加 WCSS**，因为每个观测都被指派给**当前**离它最近的质心；",
          "**更新步不会增加 WCSS**，因为在簇固定的前提下，"
          "**均值正是让平方距离之和最小的那个点**。"]),
      "重复这两步会收敛到一个**局部**解，**不一定是全局最小**。"))
A(CAL("w", "⚠ 不要从目标函数里读出它没说的东西",
      "WCSS 低只意味着：**在所选特征、所选缩放和这个 k 下，观测离各自的质心近。**",
      "它**不**显式地最大化簇间分离，也**不**证明拟合出来的组对应自然类别或有用的真实分组。"))

